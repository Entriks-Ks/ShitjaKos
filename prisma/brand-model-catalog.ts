const consoleModelAliases: Record<string, string> = {
  Xbox: "Xbox Original",
  "Nintendo 3DS": "3DS",
  "Nintendo 3DS XL": "3DS XL",
  "Nintendo 2DS": "2DS",
  "Nintendo 2DS XL": "2DS XL",
  "Nintendo DS": "DS",
  "Nintendo DS Lite": "DS Lite",
  "Atari 2600": "2600",
  "Atari 7800": "7800",
};

for (const [category, entries] of Object.entries(reference.categories)) {
  for (const entry of entries) {
    const brand = brandAliases[entry.brand] ?? entry.brand;
    const models = brandModelCatalog[category][brand] ?? [];
    for (const raw of entry.models) {
      // The seed provides translated "Other" separately for every brand.
      if (/^(andere|weiter|sonstige)/i.test(raw)) continue;
      const model = category === "gaming" ? (consoleModelAliases[raw] ?? raw) : raw;
      if (!models.some((value) => value.toLowerCase() === model.toLowerCase())) {
        models.push(model);
      }
    }
    brandModelCatalog[category][brand] = models;
  }
}
